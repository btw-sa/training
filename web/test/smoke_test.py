"""Browser smoke test of the trial copy (web/dist/index.html, data kept in the browser).

1. A fresh copy opens on the first-run setup screen (no demo accounts anywhere).
2. With the fictional test data from web/test/fixtures.js loaded into the browser, it clicks through
   every role in English and Arabic at phone and desktop widths: uploading product-card PDFs, the
   card viewer, the quiz that opens after the cards, manager scope, access, reports, data.
Fails on any page error and saves screenshots.

Usage: python3 web/test/smoke_test.py <repo-root> <screenshot-dir> [card-pdf-dir]
"""
import json
import os
import subprocess
import sys
import time
from playwright.sync_api import sync_playwright

ROOT = os.path.abspath(sys.argv[1]) if len(sys.argv) > 1 else os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
SHOTS = sys.argv[2] if len(sys.argv) > 2 else '/tmp/shots'
CARDS = sys.argv[3] if len(sys.argv) > 3 else None
PAGE = 'file://' + os.path.join(ROOT, 'web', 'dist', 'index.html')
os.makedirs(SHOTS, exist_ok=True)
errors = []

# Fictional test data, generated by the same code the engine tests use.
DEMO = subprocess.check_output(['node', '-e', "process.stdout.write(JSON.stringify(require('./web/test/fixtures.js').seedDemo(Date.now())))"], cwd=ROOT).decode('utf8')

if not CARDS:
    CARDS = os.path.join(SHOTS, '_cards')
    os.makedirs(CARDS, exist_ok=True)
    subprocess.check_call(['node', '-e', """
const { jsPDF } = require('jspdf'); const fs = require('fs'); const dir = process.argv[1];
['01 - Espresso', '02 - Flat White'].forEach((n, i) => { const d = new jsPDF({ unit: 'mm', format: [100, 140] }); d.setFontSize(22); d.text(n.slice(5), 10, 30); d.setFontSize(11); d.text('Test card ' + (i + 1), 10, 50); fs.writeFileSync(dir + '/' + n + '.pdf', Buffer.from(d.output('arraybuffer'))); });
""", CARDS], cwd=ROOT)


def lib(route):
    u = route.request.url
    if '/npm/pdfjs-dist@3.11.174/' in u:
        f = os.path.join(ROOT, 'node_modules', 'pdfjs-dist', u.split('/npm/pdfjs-dist@3.11.174/')[1].split('?')[0])
        if os.path.isfile(f):
            return route.fulfill(path=f, content_type='application/javascript' if f.endswith('.js') else 'application/octet-stream', headers={'Access-Control-Allow-Origin': '*'})
        return route.abort()
    m = {'jspdf': 'node_modules/jspdf/dist/jspdf.umd.min.js', 'qrcode': 'node_modules/qrcode-generator/qrcode.js'}
    for k, v in m.items():
        if k in u:
            return route.fulfill(path=os.path.join(ROOT, v), content_type='application/javascript')
    route.abort()


def new_context(browser, width, height, lang='en', demo=True):
    ctx = browser.new_context(viewport={'width': width, 'height': height}, accept_downloads=True)
    ctx.add_init_script(f"localStorage.setItem('btw-lang', '{lang}');")
    if demo:
        ctx.add_init_script('if (!localStorage.getItem("btw-training-v5")) localStorage.setItem("btw-training-v5", ' + json.dumps(DEMO) + ');')
    return ctx


def open_page(ctx):
    page = ctx.new_page()
    page.route('https://cdnjs.cloudflare.com/**', lib)
    page.route('https://cdn.jsdelivr.net/**', lib)
    page.route('https://fonts.googleapis.com/**', lambda r: r.abort())
    page.route('https://fonts.gstatic.com/**', lambda r: r.abort())
    page.on('pageerror', lambda e: errors.append(f'pageerror: {e}'))
    page.on('console', lambda m: errors.append(f'console.{m.type}: {m.text}') if m.type == 'error' and 'net::ERR' not in m.text and 'Failed to load resource' not in m.text else None)
    page.goto(PAGE)
    page.wait_for_selector('.login-card')
    return page


def shot(page, name):
    page.screenshot(path=os.path.join(SHOTS, name + '.png'), full_page=True)


def click(page, sel, wait=150):
    page.locator(sel).first.click()
    page.wait_for_timeout(wait)


def wait_js(page, expr, timeout=10000):
    end = time.time() + timeout / 1000
    while time.time() < end:
        if page.evaluate(expr):
            return
        page.wait_for_timeout(100)
    raise TimeoutError('timed out waiting for ' + expr)


def nav(page, route):
    page.evaluate("r => { const b = document.querySelector(`[data-act=go][data-r=\"${r}\"]`); if (b) b.click(); else throw new Error('no nav ' + r); }", route)
    page.wait_for_timeout(150)


def signin(page, ident, pw='Demo2026'):
    page.fill('#f-identifier', ident)
    page.fill('#f-password', pw)
    page.locator('form[data-form=login] button[type=submit]').click()
    page.wait_for_timeout(250)


def signout(page):
    click(page, '[data-act=openAccount]')
    click(page, '[data-act=signOut]')


def expect_text(page, text, where=''):
    if text not in page.inner_text('body'):
        errors.append(f'missing text: {text!r} {where}')


def overflow(page, label):
    ow = page.evaluate('document.documentElement.scrollWidth - document.documentElement.clientWidth')
    if ow > 1:
        errors.append(f'horizontal overflow ({label}): {ow}px')


